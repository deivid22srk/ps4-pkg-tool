/// Tamanho da entrada 0x10: seed_digest (0x20) + digest1[7] (0xE0) + key1[7] (0x700).
const ENTRY_KEYS_SIZE: usize = 0x20 + 7 * 0x20 + 7 * 0x100;
/// Deslocamento de key1[3] dentro da entrada 0x10.
const KEY1_3_OFFSET: usize = 0x20 + 7 * 0x20 + 3 * 0x100;

fn rsa_decrypt_keyset(keyset: &RsaKeyset, ciphertext: &[u8]) -> Result<[u8; 32]> {
    if ciphertext.len() != 256 {
        return Err(CoreError::InvalidPkg(format!(
            "bloco RSA de {} bytes (esperado 256)",
            ciphertext.len()
        )));
    }
    let n = BigUint::from_bytes_be(keyset.modulus);
    let e = BigUint::from_bytes_be(keyset.public_exponent);
    let d = BigUint::from_bytes_be(keyset.private_exponent);
    let p = BigUint::from_bytes_be(keyset.prime1);
    let q = BigUint::from_bytes_be(keyset.prime2);
    let private = RsaPrivateKey::from_components(n, e, d, vec![p, q]).map_err(|err| {
        CoreError::Internal(format!("keyset {} inválido: {err}", keyset.name))
    })?;
    debug_assert_eq!(
        private.size(),
        256,
        "módulo RSA do keyset {} deveria ter 2048 bits",
        keyset.name
    );
    let plain = private.decrypt(Pkcs1v15Encrypt, ciphertext).map_err(|_| {
        CoreError::EncryptedPkg(format!(
            "falha ao decifrar bloco RSA com o keyset {} — PKG não suportado",
            keyset.name
        ))
    })?;
    if plain.len() < 32 {
        return Err(CoreError::EncryptedPkg(format!(
            "bloco RSA do keyset {} decifrou {} bytes (esperado >= 32)",
            keyset.name,
            plain.len()
        )));
    }
    let mut out = [0u8; 32];
    out.copy_from_slice(&plain[..32]);
    Ok(out)
}

/// AES-128-CBC in-place, sem remoção de padding (shadPS4 usa ProcessData em
/// blocos completos e mantém o ciphertext final intacto).
fn aes128_cbc_decrypt(key: &[u8; 16], iv: &[u8; 16], data: &mut [u8]) -> Result<()> {
    if data.len() % 16 != 0 {
        return Err(CoreError::InvalidPkg(
            "dados AES-CBC não são múltiplos de 16".into(),
        ));
    }
    let cipher = Aes128::new(GenericArray::from_slice(key));
    let mut previous = *iv;
    for chunk in data.chunks_exact_mut(16) {
        let mut block = *GenericArray::from_slice(chunk);
        let ciphertext_block = block;
        cipher.decrypt_block(&mut block);
        for (index, value) in previous.iter().enumerate() {
            block[index] ^= value;
        }
        chunk.copy_from_slice(&block);
        previous = ciphertext_block.into();
    }
    Ok(())
}

/// Deriva o `ekpfs` (32 bytes) de um PKG comercial, seguindo a mesma cadeia do
/// shadPS4 (`PKG::Extract`, entradas 0x10 e 0x20):
///
/// 1. `dk3` = RSA-PKCS1v15-decrypt(key1[3], PkgDerivedKey3Keyset)
/// 2. `ivKey` = SHA256(linha bruta de 0x20 na tabela de entradas || dk3)
/// 3. `imgKey` = AES-128-CBC-decrypt(imgkeydata, ivKey)
/// 4. `ekpfs` = RSA-PKCS1v15-decrypt(imgKey, FakeKeyset)
///
/// O `ekpfs` retornado é a chave HMAC que, combinada com o `key_seed` do
/// cabeçalho PFS, produz os pares XTS (dataKey, tweakKey) — exatamente o que
/// `orbis_pfs::open_slice` espera no parâmetro `ekpfs`.
pub fn derive_ekpfs(data: &[u8], header: &PkgHeader) -> Result<[u8; 32]> {
    let entries = parse_entries(data, header)?;

    let keys_entry = entries
        .iter()
        .find(|entry| entry.id == PKG_ENTRY_ID_ENTRY_KEYS)
        .ok_or_else(|| {
            CoreError::EncryptedPkg(
                "PKG não possui a entrada 0x10 (ENTRY_KEYS); não é possível derivar chaves".into(),
            )
        })?;
    if (keys_entry.data_size as usize) < ENTRY_KEYS_SIZE {
        return Err(CoreError::EncryptedPkg(format!(
            "entrada 0x10 com {} bytes (esperado >= {ENTRY_KEYS_SIZE:#x})",
            keys_entry.data_size
        )));
    }
    let keys_start = keys_entry.data_offset as usize;
    let key1_3: &[u8] = &data[keys_start + KEY1_3_OFFSET..keys_start + KEY1_3_OFFSET + 256];
    let dk3 = rsa_decrypt_keyset(&PKG_DERIVED_KEY3_KEYSET, key1_3)?;

    let (image_index, image_entry) = entries
        .iter()
        .enumerate()
        .find(|(_, entry)| entry.id == PKG_ENTRY_ID_IMAGE_KEY)
        .ok_or_else(|| {
            CoreError::EncryptedPkg(
                "PKG não possui a entrada 0x20 (IMAGE_KEY); não é possível derivar chaves".into(),
            )
        })?;
    if (image_entry.data_size as usize) < 256 {
        return Err(CoreError::EncryptedPkg(format!(
            "entrada 0x20 com {} bytes (esperado >= 0x100)",
            image_entry.data_size
        )));
    }

    // A linha bruta de 0x20 bytes da tabela de entradas participa do hash —
    // shadPS4 faz memcpy(&entry, sizeof(PKGEntry)) sobre a struct lida do
    // arquivo, ou seja, os bytes big-endian como estão na tabela.
    let row_offset = header.table_offset as usize + image_index * 0x20;
    let row: &[u8] = &data[row_offset..row_offset + 0x20];

    let image_start = image_entry.data_offset as usize;
    let mut img_key_block: [u8; 256] =
        data[image_start..image_start + 256].try_into().unwrap();

    let mut hasher = Sha256::new();
    hasher.update(row);
    hasher.update(&dk3);
    let iv_key: [u8; 32] = hasher.finalize().into();

    let aes_key: [u8; 16] = iv_key[16..32].try_into().unwrap();
    let aes_iv: [u8; 16] = iv_key[0..16].try_into().unwrap();
    aes128_cbc_decrypt(&aes_key, &aes_iv, &mut img_key_block)?;

    rsa_decrypt_keyset(&FAKE_KEYSET, &img_key_block)
}

