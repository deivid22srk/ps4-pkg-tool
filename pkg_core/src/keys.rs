    fn keyset_parts(keyset: &RsaKeyset) -> (BigUint, BigUint, BigUint, BigUint, BigUint) {
        (
            BigUint::from_bytes_be(keyset.modulus),
            BigUint::from_bytes_be(keyset.public_exponent),
            BigUint::from_bytes_be(keyset.private_exponent),
            BigUint::from_bytes_be(keyset.prime1),
            BigUint::from_bytes_be(keyset.prime2),
        )
    }

    #[test]
    fn rsa_keysets_are_consistent() {
        for keyset in [&FAKE_KEYSET, &PKG_DERIVED_KEY3_KEYSET] {
            let (n, e, d, p, q) = keyset_parts(keyset);
            assert_eq!(&p * &q, n, "{}: p*q != n", keyset.name);
            let phi = (&p - 1u8) * (&q - 1u8);
            assert_eq!(
                (&e * &d) % &phi,
                BigUint::from(1u8),
                "{}: e*d != 1 mod phi",
                keyset.name
            );
            assert_eq!(n.bits(), 2048, "{}: módulo não é 2048 bits", keyset.name);
        }
    }

