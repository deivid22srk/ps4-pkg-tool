    #[test]
    fn derive_ekpfs_synthetic_pkg() {
        use aes::cipher::BlockEncrypt;
        // Monta um PKG sintético com entradas 0x10/0x20 no formato comercial
        // (shadPS4) e verifica que derive_ekpfs recupera o ekpfs escolhido.
        let ekpfs: [u8; 32] = core::array::from_fn(|i| (i as u8).wrapping_mul(91).wrapping_add(7));
        let dk3: [u8; 32] = core::array::from_fn(|i| (i as u8).wrapping_mul(53).wrapping_add(11));

        // key1[3] = PKCS1v15(dk3) com a chave pública do keyset 3
        let key1_3 = pkcs1v15_encrypt(&PKG_DERIVED_KEY3_KEYSET, &dk3);
        // imgKey = PKCS1v15(ekpfs) com a chave pública do FakeKeyset
        let img_key = pkcs1v15_encrypt(&FAKE_KEYSET, &ekpfs);

        // Entradas: 0x10 em offset 0x1000, 0x20 em 0x2000
        let entry_keys_offset: u32 = 0x1000;
        let image_key_offset: u32 = 0x2000;

        let mut entries: Vec<[u8; 0x20]> = Vec::new();
        let mut push_entry = |id: u32, offset: u32, size: u32| {
            let mut row = [0u8; 0x20];
            row[0..4].copy_from_slice(&id.to_be_bytes());
            row[16..20].copy_from_slice(&offset.to_be_bytes());
            row[20..24].copy_from_slice(&size.to_be_bytes());
            entries.push(row);
        };
        push_entry(PKG_ENTRY_ID_ENTRY_KEYS, entry_keys_offset, ENTRY_KEYS_SIZE as u32);
        push_entry(PKG_ENTRY_ID_IMAGE_KEY, image_key_offset, 0x100);

        // imgkeydata = AES-128-CBC-ENCRYPT(ivKey, imgKey) — espelha o formato
        // comercial: a entrada 0x20 guarda o blob cifrado, e a derivação o
        // decifra antes do RSA.
        let mut hasher = Sha256::new();
        hasher.update(&entries[1]);
        hasher.update(&dk3);
        let iv_key: [u8; 32] = hasher.finalize().into();
        let mut imgkeydata = img_key.clone();
        {
            let cipher = Aes128::new(GenericArray::from_slice(&iv_key[16..32]));
            let mut previous: [u8; 16] = iv_key[0..16].try_into().unwrap();
            for chunk in imgkeydata.chunks_exact_mut(16) {
                let mut block = *GenericArray::from_slice(chunk);
                for (index, value) in previous.iter().enumerate() {
                    block[index] ^= value;
                }
                cipher.encrypt_block(&mut block);
                chunk.copy_from_slice(&block);
                previous.copy_from_slice(chunk);
            }
        }

        // Cabeçalho: magic + entry_count + table_offset (lidos por PkgHeader::parse)
        let mut header = vec![0u8; 0x1000];
        header[0..4].copy_from_slice(&PKG_MAGIC.to_be_bytes());
        header[0x10..0x14].copy_from_slice(&(entries.len() as u32).to_be_bytes());
        header[0x18..0x1c].copy_from_slice(&0x800u32.to_be_bytes()); // table_offset

        let mut data = header.clone();
        // Corpo: entrada 0x10 em 0x1000 (0x800 bytes) e entrada 0x20 em 0x2000 (0x100)
        let mut body = vec![0u8; 0x1000];
        body[KEY1_3_OFFSET..KEY1_3_OFFSET + 256].copy_from_slice(&key1_3);
        data.extend_from_slice(&body);
        data.extend_from_slice(&imgkeydata);

        // Linha bruta da entrada 0x20 na tabela
        let mut pkg = data.clone();
        let table_offset = 0x800usize;
        for (i, row) in entries.iter().enumerate() {
            let at = table_offset + i * 0x20;
            pkg[at..at + 0x20].copy_from_slice(row);
        }

        let parsed = PkgHeader::parse(&pkg).unwrap();
        let derived = derive_ekpfs(&pkg, &parsed).unwrap();
        assert_eq!(derived, ekpfs);
    }

    fn pkcs1v15_encrypt(keyset: &RsaKeyset, message: &[u8]) -> Vec<u8> {
        use rsa::rand_core::OsRng;
        use rsa::RsaPublicKey;
        let n = BigUint::from_bytes_be(keyset.modulus);
        let e = BigUint::from_bytes_be(keyset.public_exponent);
        let public = RsaPublicKey::new(n, e).expect("chave pública de teste inválida");
        public
            .encrypt(&mut OsRng, Pkcs1v15Encrypt, message)
            .expect("falha ao cifrar mensagem de teste")
    }
